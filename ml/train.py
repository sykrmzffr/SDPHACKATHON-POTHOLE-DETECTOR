"""
Train JalanSense road-event classifiers.

Two models are produced:
  1. Edge model  - a small decision tree (depth <= 6). Exported as
       firmware/jalansense_node/model.h   (runs on the ESP32, no libraries)
       web/js/model.json                  (runs in the phone drive mode)
  2. Cloud model - a random forest, used server-side to re-check events
       (higher accuracy, can be retrained as real labelled data arrives).

Usage:
    python generate_data.py
    python train.py                       # uses data/synthetic.csv
    python train.py --data data/real.csv  # once pilot data exists
"""
import argparse
import json
import os

import joblib
import numpy as np
import pandas as pd
from sklearn.ensemble import RandomForestClassifier
from sklearn.metrics import classification_report, confusion_matrix
from sklearn.model_selection import train_test_split
from sklearn.tree import DecisionTreeClassifier

from features import FEATURE_NAMES

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)


def tree_to_dict(clf):
    t = clf.tree_
    return {
        "features": FEATURE_NAMES,
        "classes": [str(c) for c in clf.classes_],
        "feature": t.feature.tolist(),
        "threshold": [round(float(x), 5) for x in t.threshold],
        "left": t.children_left.tolist(),
        "right": t.children_right.tolist(),
        "value": [int(np.argmax(v)) for v in t.value[:, 0, :]],
    }


def tree_to_c(clf):
    t = clf.tree_
    classes = [str(c) for c in clf.classes_]
    lines = [
        "// Auto-generated by ml/train.py - do not edit by hand.",
        "#pragma once",
        f"#define JS_N_FEATURES {len(FEATURE_NAMES)}",
        "// feature order: " + ", ".join(FEATURE_NAMES),
        "static const char* JS_CLASSES[] = {" + ", ".join(f'"{c}"' for c in classes) + "};",
        "",
        "static int js_classify(const float* f) {",
    ]

    def rec(node, depth):
        pad = "  " * depth
        if t.children_left[node] == -1:
            lines.append(f"{pad}return {int(np.argmax(t.value[node][0]))};  // {classes[int(np.argmax(t.value[node][0]))]}")
            return
        lines.append(f"{pad}if (f[{t.feature[node]}] <= {t.threshold[node]:.5f}f) {{  // {FEATURE_NAMES[t.feature[node]]}")
        rec(t.children_left[node], depth + 1)
        lines.append(f"{pad}}} else {{")
        rec(t.children_right[node], depth + 1)
        lines.append(f"{pad}}}")

    rec(0, 1)
    lines.append("}")
    return "\n".join(lines) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--data", default=os.path.join(HERE, "data", "synthetic.csv"))
    ap.add_argument("--depth", type=int, default=6)
    a = ap.parse_args()

    df = pd.read_csv(a.data)
    X, y = df[FEATURE_NAMES].values, df["label"].values
    Xtr, Xte, ytr, yte = train_test_split(X, y, test_size=0.25, stratify=y, random_state=1)

    edge = DecisionTreeClassifier(max_depth=a.depth, min_samples_leaf=10, random_state=1).fit(Xtr, ytr)
    cloud = RandomForestClassifier(n_estimators=200, min_samples_leaf=2, random_state=1, n_jobs=-1).fit(Xtr, ytr)

    out = {}
    for name, m in (("edge_tree", edge), ("cloud_forest", cloud)):
        p = m.predict(Xte)
        rep = classification_report(yte, p, output_dict=True, zero_division=0)
        cm = confusion_matrix(yte, p, labels=m.classes_)
        out[name] = {
            "accuracy": round(rep["accuracy"], 4),
            "pothole_precision": round(rep["pothole"]["precision"], 4),
            "pothole_recall": round(rep["pothole"]["recall"], 4),
            "speed_bump_recall": round(rep["speed_bump"]["recall"], 4),
            "labels": list(m.classes_),
            "confusion_matrix": cm.tolist(),
        }
        print(f"\n=== {name} ===")
        print(classification_report(yte, p, zero_division=0))
        print("confusion (rows=true, cols=pred)", list(m.classes_))
        print(cm)

    imp = sorted(zip(FEATURE_NAMES, cloud.feature_importances_), key=lambda x: -x[1])
    out["feature_importance"] = [[n, round(float(v), 4)] for n, v in imp]
    out["n_train"], out["n_test"], out["data"] = len(Xtr), len(Xte), os.path.basename(a.data)

    os.makedirs(os.path.join(HERE, "models"), exist_ok=True)
    os.makedirs(os.path.join(HERE, "results"), exist_ok=True)
    joblib.dump(cloud, os.path.join(HERE, "models", "cloud_forest.joblib"))
    joblib.dump(edge, os.path.join(HERE, "models", "edge_tree.joblib"))
    with open(os.path.join(HERE, "results", "metrics.json"), "w") as f:
        json.dump(out, f, indent=2)

    fw = os.path.join(ROOT, "firmware", "jalansense_node", "model.h")
    os.makedirs(os.path.dirname(fw), exist_ok=True)
    with open(fw, "w") as f:
        f.write(tree_to_c(edge))
    web = os.path.join(ROOT, "web", "js", "model.json")
    os.makedirs(os.path.dirname(web), exist_ok=True)
    with open(web, "w") as f:
        json.dump(tree_to_dict(edge), f)

    try:
        import matplotlib
        matplotlib.use("Agg")
        import matplotlib.pyplot as plt
        cm = np.array(out["cloud_forest"]["confusion_matrix"])
        labs = out["cloud_forest"]["labels"]
        fig, ax = plt.subplots(figsize=(5, 4.2))
        ax.imshow(cm, cmap="Blues")
        ax.set_xticks(range(len(labs)), labs, rotation=30)
        ax.set_yticks(range(len(labs)), labs)
        for i in range(len(labs)):
            for j in range(len(labs)):
                ax.text(j, i, cm[i, j], ha="center", va="center",
                        color="white" if cm[i, j] > cm.max() / 2 else "black")
        ax.set_xlabel("Predicted"); ax.set_ylabel("Actual")
        ax.set_title("Road-event classifier (test set)")
        fig.tight_layout()
        fig.savefig(os.path.join(HERE, "results", "confusion_matrix.png"), dpi=160)
    except Exception as e:  # plotting is optional
        print("plot skipped:", e)

    print("\nSaved models/, results/metrics.json, firmware model.h, web model.json")


if __name__ == "__main__":
    main()
